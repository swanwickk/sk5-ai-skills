def _snap(v, keys):
    return min(keys, key=lambda k: (abs(k - v), k))
def _col(angle):
    return X_ANGLES.index(_snap(angle, X_ANGLES))

def x4_belt_adj(belt_inch):
    for lim, adj in [(1.0, -1), (3.0, -2), (5.0, -3), (8.0, -4), (11.0, -5), (15.0, -6)]:
        if belt_inch <= lim:
            return adj
    return -7
X4_TYPE_ADJ = {'W25': 0, 'W06': 1, 'W80': 2, 'SUB': 1, 'NONWAR': 3}
X5_TGT_ADJ = [('NONWAR', -3), ('NOBELT', -1), (2.0, 1), (6.0, 2), (12.0, 3), (float('inf'), 4)]
X5_RAM_ADJ = {'RAM': -5, 'ARMORED': -3, 'TRUERAM': -6, 'OTHER': 0}

def ram_damage(tgt_speed, ram_speed, angle, tgt_belt, tgt_type='W25',
               tgt_total_dp=0, ram_has='OTHER', tgt_armor_key='BELT'):
    """撞击结算。撞击因数=X1+X2；X4/X5为X3行上下调整。返回dict。"""
    f1 = X1_TABLE[_snap(tgt_speed, X1_TABLE)][_col(angle)]
    f2 = X2_TABLE[_snap(ram_speed, X2_TABLE)][_col(angle)]
    impact = f1 + f2
    if impact <= 0:
        return {'impact': impact, 'dp': 0, 'note': '因数<=0无作用'}
    r1 = _snap(impact + x4_belt_adj(tgt_belt) + X4_TYPE_ADJ.get(tgt_type, 0), X3_TABLE)
    df = X3_TABLE[r1][_col(angle)]
    if df is None:
        return {'impact': impact, 'dp': 0, 'note': 'X3为N/A无作用'}
    dp = df * tgt_total_dp
    if tgt_armor_key == 'NOBELT':
        ta = -1
    elif tgt_armor_key == 'NONWAR':
        ta = -3
    else:
        ta = 1 if tgt_belt <= 2.0 else (2 if tgt_belt <= 6.0 else (3 if tgt_belt <= 12.0 else 4))
    r2 = _snap(impact + ta + X5_RAM_ADJ.get(ram_has, 0), X3_TABLE)
    df2 = X3_TABLE[r2][_col(angle)]
    ram_dp = (df2 or 0) * dp
    return {'impact': impact, 'x3row': r1, 'factor': df, 'dp': dp,
            'ram_x3row': r2, 'ram_factor': df2, 'ram_dp': ram_dp}

