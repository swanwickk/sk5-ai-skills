# ---- M2 严重度初值：掷骰+炮弹口径英寸数，>=100 转永久 ----
def severity_init(roll, shell_inch):
    return roll + shell_inch

# ---- M3 损伤状态检定 ----
def m3_check(roll, severity, dc_applied):
    eff = roll if dc_applied else roll - 20
    if eff > severity:
        return 'repaired'
    if (dc_applied and roll <= 2) or (not dc_applied and roll <= 7):
        return 'permanent'
    return 'continues'

# ---- M4 士气检定：tier -> crew -> (lo,hi) 或 None(不检定) ----
M4_TABLE = {
    7:  {'-1': (1, 12), '0+1': (1, 8), '+2': (1, 4), '+3': None},
    8:  {'-1': (1, 24), '0+1': (1, 16), '+2': (1, 10), '+3': (1, 4)},
    9:  {'-1': (1, 36), '0+1': (1, 24), '+2': (1, 15), '+3': (1, 8)},
    10: {'-1': (1, 48), '0+1': (1, 32), '+2': (1, 20), '+3': (1, 15)},
}
def m4_check(tier, crew, roll):
    rng = M4_TABLE[tier]['-1' if crew <= -1 else ('+3' if crew >= 3 else ('+2' if crew == 2 else '0+1'))]
    if rng is None:
        return False
    return rng[0] <= roll <= rng[1]

# ---- M7 脱离后修理 ----
def m7_repair(roll):
    if roll <= 25:
        return 'inport'
    if roll <= 90:
        return 'unrepaired'
    return 'repaired'

# ---- N1 灭火：返回 ('out',) 或 ('delta', +/-n) ----
N1_NODC = [(1, 3, -20), (4, 12, -10), (13, 50, 0), (51, 85, 10), (86, 95, 30), (96, 100, 40)]
N1_DC = [(1, 5, 'out'), (6, 15, -30), (16, 45, -20), (46, 75, -10), (76, 90, 0), (91, 100, 10)]
def n1_fight(roll, dc_applied):
    for lo, hi, eff in (N1_DC if dc_applied else N1_NODC):
        if lo <= roll <= hi:
            return ('out',) if eff == 'out' else ('delta', eff)
    return None

# ---- N2 火灾致DE：取不大于火势严重度的最高档 ----
N2_ROWS = [(50, 20), (60, 25), (70, 30), (80, 35), (90, 40), (100, 50)]
def n2_fire_de(severity, roll):
    if severity < 50:
        return False
    th = max(t for t, _ in N2_ROWS if t <= severity)
    lim = dict(N2_ROWS)[th]
    return roll <= lim

