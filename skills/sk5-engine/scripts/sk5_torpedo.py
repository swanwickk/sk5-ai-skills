def check_dud(country, is_mag=False, date=None):
    """T4哑弹阈值。date=目标年月（'YYYY-MM'或'YYYY'）时按年份段匹配，不传则取该国首条。
    年份段取端点年份比较，忽略月份（段边界均为整年附近）。"""
    import re
    rows = [(c, s, cd, md) for c, s, cd, md in T4_DUD if c == country]
    if not rows:
        return 15
    if date:
        y = int(re.findall(r'\d{4}', str(date))[0])
        for c, s, cd, md in rows:
            ys = [int(v) for v in re.findall(r'\d{4}', s)]
            if ys[0] <= y <= ys[1]:
                return md if is_mag else cd
    c, s, cd, md = rows[0]
    return md if is_mag else cd

